<?php
declare(strict_types=1);

namespace Momos\Presentation\Maintenance;

use Momos\Kernel\I18n\Lang;
use Momos\Presentation\View\Brand;

/**
 * SCR-C20 maintenance page (ui-design-system.md §8.12, FR-CORP-007, AC-CORP-07-02). Generates a fully
 * static PHP drop-in: HTTP 503 + `Retry-After: 600`, inline CSS with literal token values, system fonts
 * only, inline SVG wordmark, one block per enabled language with its own `lang`/`dir`, optional brand
 * contact phone (G1 `momo_contact_phone_e164` + its display form `momo_contact_phone_display`, FR-FND-005 —
 * omitted while empty). No WordPress needed at render time. Export at each release:
 * `wp momos maintenance-page [--path=<file>]`. The ROLE-01 Settings toggle (MaintenanceMode) serves document().
 */
final class MaintenancePage {
	public const RETRY_AFTER = 600;

	/**
	 * Static PHP drop-in: response headers + document().
	 *
	 * @param list<string>|null $langs
	 */
	public static function html( ?array $langs = null, ?string $phone_e164 = null ): string {
		return "<?php\n/* Generated by Momos\\Presentation\\Maintenance\\MaintenancePage — SCR-C20. Do not edit; re-export with `wp momos maintenance-page`. */\n"
			. "if ( ! headers_sent() ) { http_response_code( 503 ); header( 'Retry-After: " . self::RETRY_AFTER . "' ); header( 'Content-Type: text/html; charset=utf-8' ); header( 'Cache-Control: no-store' ); header( 'X-Robots-Tag: noindex' ); }\n?>"
			. self::document( $langs, $phone_e164 );
	}

	/**
	 * Brand contact phone for the page: [E.164, display] from G1 (FR-FND-005); display falls back to E.164.
	 *
	 * @return array{0:string,1:string}
	 */
	public static function phone( ?string $phone_e164 = null ): array {
		$e164    = $phone_e164 ?? (string) Brand::option( 'momo_contact_phone_e164' );
		$e164    = preg_match( '/^\+[1-9]\d{6,14}$/', $e164 ) ? $e164 : '';
		$display = null === $phone_e164 ? trim( (string) Brand::option( 'momo_contact_phone_display' ) ) : '';
		return [ $e164, '' !== $e164 && '' !== $display ? $display : $e164 ];
	}

	/**
	 * The HTML document (no PHP) — every enabled language in its own `lang`/`dir` block.
	 *
	 * @param list<string>|null $langs
	 */
	public static function document( ?array $langs = null, ?string $phone_e164 = null ): string {
		$langs  = $langs ?? Lang::enabled();
		[ $phone, $shown ] = self::phone( $phone_e164 );
		$fonts  = [
			'ja' => '"Hiragino Sans","Yu Gothic","Meiryo",sans-serif',
			'ar' => 'Tahoma,"Segoe UI",sans-serif',
			'ur' => 'Tahoma,"Segoe UI",sans-serif',
			'hi' => '"Nirmala UI",sans-serif',
			'bn' => '"Nirmala UI",sans-serif',
			'en' => 'system-ui,-apple-system,"Segoe UI",Arial,sans-serif',
		];
		$blocks = '';
		foreach ( $langs as $code ) {
			if ( ! Lang::is_valid( $code ) ) {
				continue;
			}
			$dir     = Lang::is_rtl( $code ) ? 'rtl' : 'ltr';
			$lh      = 'ur' === $code ? '2' : ( 'en' === $code ? '1.6' : '1.8' );
			$blocks .= sprintf(
				'<section lang="%1$s" dir="%2$s" style="font-family:%3$s;line-height:%4$s"><h2>%5$s</h2><p>%6$s</p>%7$s</section>' . "\n",
				esc_attr( Lang::ALL[ $code ]['html'] ),
				$dir,
				esc_attr( $fonts[ $code ] ?? $fonts['en'] ),
				$lh,
				esc_html( momos_t( 'maintenance.title', [], $code ) ),
				esc_html( momos_t( 'maintenance.body', [], $code ) ),
				'' !== $phone ? '<p>' . str_replace( '{phone}', '<a href="tel:' . esc_attr( $phone ) . '"><bdi dir="ltr">' . esc_html( $shown ) . '</bdi></a>', esc_html( momos_t( 'maintenance.phone', [], $code ) ) ) . '</p>' : ''
			);
		}
		$title = esc_html( momos_t( 'maintenance.title', [], 'ja' ) . ' / ' . momos_t( 'maintenance.title', [], 'en' ) );
		$logo  = self::wordmark();
		$css   = 'html{color-scheme:light}body{margin:0;background:#FAF3EB;color:#221A17;font-family:system-ui,sans-serif;font-size:16px}'
			. 'main{max-width:720px;margin:0 auto;padding:48px 16px}header{text-align:center;margin-bottom:32px}header svg{height:56px;width:auto}'
			. 'section{background:#FFFFFF;border:1px solid #EED0B8;border-radius:24px;padding:20px 24px;margin-block-end:16px}'
			. 'h2{font-size:1.25rem;margin:0 0 8px;color:#1E3D34}p{margin:0 0 8px}a{color:#A03B00;text-decoration:underline}'
			. 'a:focus-visible{outline:2px solid #1E3D34;outline-offset:2px}';
		return "<!doctype html>\n<html lang=\"ja\" dir=\"ltr\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\"><meta name=\"robots\" content=\"noindex\"><title>{$title}</title><style>{$css}</style></head>\n"
			. "<body><main><header>{$logo}</header>\n{$blocks}</main></body></html>\n";
	}

	/** Inline outlined wordmark (no font dependency), from the theme sprite symbols. */
	public static function wordmark(): string {
		$sprite = function_exists( 'get_theme_file_path' ) ? get_theme_file_path( 'assets/icons/sprite.svg' ) : '';
		$svg    = is_file( $sprite ) ? (string) file_get_contents( $sprite ) : ''; // phpcs:ignore WordPress.WP.AlternativeFunctions
		if ( ! preg_match( '/<symbol id="logo-word" viewBox="([^"]+)"><path d="([^"]+)"/', $svg, $w ) || ! preg_match( '/<symbol id="logo-tag" viewBox="[^"]+"><path d="([^"]+)"/', $svg, $t ) ) {
			return '<p style="font:800 2rem system-ui,sans-serif">MOMO&#8217;s</p>';
		}
		return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="' . esc_attr( $w[1] ) . '" role="img" aria-label="' . esc_attr( Brand::PROVISIONAL_NAME ) . '"><path fill="#221A17" d="' . esc_attr( $w[2] ) . '"/><path fill="#1E3D34" d="' . esc_attr( $t[1] ) . '"/></svg>';
	}

	public static function export( string $path ): bool {
		$dir = dirname( $path );
		if ( ! is_dir( $dir ) || ! is_writable( $dir ) ) {
			return false;
		}
		return false !== file_put_contents( $path, self::html() ); // phpcs:ignore WordPress.WP.AlternativeFunctions
	}
}
